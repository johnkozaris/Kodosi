enum TerminalHardwareKeyMap {
    static let unidentifiedKeyCode: UInt32 = 0x10000

    static func keyCode(forHIDUsage usage: UInt16) -> UInt32 {
        macKeyCodes[usage].map(UInt32.init) ?? unidentifiedKeyCode
    }

    static func isModifier(hidUsage usage: UInt16) -> Bool {
        (0xE0 ... 0xE7).contains(usage)
    }

    static func character(forHIDUsage usage: UInt16, shifted: Bool) -> Character? {
        guard let characters = usLayout[usage] else { return nil }
        return shifted ? characters.shifted : characters.base
    }

    static func hidUsage(for character: Character) -> (usage: UInt16, shifted: Bool)? {
        usLayoutUsages[character]
    }

    static let macKeyCodes: [UInt16: UInt16] = [
