    ]

    private static let usLayout: [UInt16: (base: Character, shifted: Character)] = {
        var layout: [UInt16: (base: Character, shifted: Character)] = [:]
        for (offset, letter) in "abcdefghijklmnopqrstuvwxyz".enumerated() {
            layout[0x04 + UInt16(offset)] = (letter, Character(letter.uppercased()))
        }
        for (offset, characters) in zip("1234567890", "!@#$%^&*()").enumerated() {
            layout[0x1E + UInt16(offset)] = (characters.0, characters.1)
        }
        let symbols: [(UInt16, Character, Character)] = [
            (0x2C, " ", " "),
            (0x2D, "-", "_"),
            (0x2E, "=", "+"),
            (0x2F, "[", "{"),
            (0x30, "]", "}"),
            (0x31, "\\", "|"),
            (0x33, ";", ":"),
            (0x34, "'", "\""),
            (0x35, "`", "~"),
            (0x36, ",", "<"),
            (0x37, ".", ">"),
            (0x38, "/", "?"),
        ]
        for (usage, base, shifted) in symbols {
            layout[usage] = (base, shifted)
        }
        return layout
    }()

    private static let usLayoutUsages: [Character: (usage: UInt16, shifted: Bool)] = {
        var usages: [Character: (usage: UInt16, shifted: Bool)] = [:]
        for (usage, characters) in usLayout {
            usages[characters.base] = (usage, false)
            if characters.shifted != characters.base {
                usages[characters.shifted] = (usage, true)
            }
        }
        return usages
    }()
}
